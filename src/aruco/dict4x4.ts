// 黒い枠を含む 6×6（1 = 明るい = ステッカーの色、0 = 黒）
export function markerBits(id: number): Uint8Array {
  const v = DICT_4X4_100[id];
  const out = new Uint8Array(36);
  for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) out[(r + 1) * 6 + c + 1] = (v >> (15 - (r * 4 + c))) & 1;
  return out;
}
